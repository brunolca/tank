export type BossKind = 'boss' | 'drill' | 'thunder' | 'sower' | 'bombard' | 'train';
/**
 * Which boss holds a boss mission, in turn: the Colosse (10, 110, 210…), the Foreur (20, 70, 120…), the Grondeur
 * (30, 80, 130…), the Semeur (40, 90, 140…), since iteration 35 the Bombardier (50, 100, 150…) and, since
 * iteration 49, the Tortillard, which took over every other Colosse (60, 160, 260…).
 */
export function bossOf(mission: number): BossKind {
  const k = Math.round(mission / 10) % 5;
  if (k === 1 && Math.floor(mission / 50) % 2 === 1) return 'train';
  return k === 2 ? 'drill' : k === 3 ? 'thunder' : k === 4 ? 'sower' : k === 0 ? 'bombard' : 'boss';
}

/** The Tortillard's station for a boss mission (or the boss round): the train on its rails, and two escorts. */
export function trainLevel(mission: number, arena = 0): ParsedLevel {
  const lvl = parseLevel({ name: `Le Tortillard · ${mission}`, map: TRAIN_ARENAS[arena % TRAIN_ARENAS.length] });
  lvl.rail = TRAIN_RAIL.slice();
  const [x, y] = TRAIN_START;
  lvl.enemies.push({ kind: 'train', x, y });
  for (let i = 0; i < TRAIN_WAGONS; i++) lvl.enemies.push({ kind: 'wagon', x, y }); // the rails place them behind it
  const esc = BOSS_ESCORTS[Math.min(BOSS_ESCORTS.length - 1, Math.floor(mission / 10) - 2)];
  lvl.enemies.push({ kind: esc[0], x: 20.5, y: 2.5 }, { kind: esc[1], x: 20.5, y: 14.5 });
  return lvl;
}

/** Endless-mode boss fights: an open arena, the boss and two escorts that get nastier. */
export function bossLevel(mission: number, who: BossKind = bossOf(mission)): ParsedLevel {
  const cycle = Math.floor(mission / 50); // how many times the five bosses came round already
  if (who === 'train') {
    // the second station is the night one (160, 360…): only the locomotive's lamp and the wagons' lanterns show the way
    const lvl = trainLevel(mission, cycle % 4 === 3 ? 1 : 0);
    if (cycle % 4 === 3) { lvl.night = true; lvl.name = `Le Tortillard de nuit · ${mission}`; }
    return lvl;
  }
  if (who === 'bombard') {
    const lvl = parseLevel({ name: `Le Bombardier · ${mission}`, map: BOMBARD_ARENAS[Math.max(0, cycle - 1) % BOMBARD_ARENAS.length] });
    const esc = BOSS_ESCORTS[Math.min(BOSS_ESCORTS.length - 1, Math.floor(mission / 10) - 2)];
    lvl.enemies.push({ kind: esc[0], x: 16.5, y: 2.5 }, { kind: esc[1], x: 16.5, y: 14.5 });
    // every other battery shells you at night, from the 100th (100, 200…): only the red rings light the way
    if (mission >= 100 && cycle % 2 === 0) { lvl.night = true; lvl.name = `Le Bombardier de nuit · ${mission}`; }
    return lvl;
  }
  if (who === 'sower') {
    const lvl = parseLevel({ name: `Le Semeur · ${mission}`, map: SOWER_ARENAS[cycle % SOWER_ARENAS.length] });
    const esc = BOSS_ESCORTS[Math.min(BOSS_ESCORTS.length - 1, Math.floor(mission / 10) - 2)];
    lvl.enemies.push({ kind: esc[0], x: 19.5, y: 2.5 }, { kind: esc[1], x: 19.5, y: 14.5 });
    // every other field is sown in the wind, from the second time round (90, 190…; it blows down the table)
    if (cycle % 2 === 1) { lvl.wind = Math.PI / 2; lvl.name = `Le Semeur dans le vent · ${mission}`; }
    return lvl;
  }
  if (who === 'thunder') {
    const lvl = parseLevel({ name: `Le Grondeur · ${mission}`, map: THUNDER_ARENAS[cycle % THUNDER_ARENAS.length], storm: true });
    const esc = BOSS_ESCORTS[Math.min(BOSS_ESCORTS.length - 1, Math.floor(mission / 10) - 2)];
    lvl.enemies.push({ kind: esc[0], x: 19.5, y: 4.5 }, { kind: esc[1], x: 19.5, y: 12.5 });
    return lvl; // a storm sky: once the Grondeur falls, its lightning runs wild until the mission ends
  }
  if (who === 'drill') {
    const lvl = parseLevel({ name: `Le Foreur · ${mission}`, map: DRILL_ARENAS[cycle % DRILL_ARENAS.length] });
    const esc = BOSS_ESCORTS[Math.min(BOSS_ESCORTS.length - 1, Math.floor(mission / 10) - 2)];
    lvl.enemies.push({ kind: esc[0], x: 19.5, y: 2.5 }, { kind: esc[1], x: 19.5, y: 14.5 });
    return lvl; // always by day: you need to see the ground shake
  }
  const lvl = parseLevel({ name: `Le Colosse · ${mission}`, map: BOSS_ARENAS[(mission / 10) % BOSS_ARENAS.length] });
  const esc = BOSS_ESCORTS[Math.min(BOSS_ESCORTS.length - 1, Math.floor(mission / 10) - 2)];
  lvl.enemies.push({ kind: esc[0], x: 18.5, y: 3.5 }, { kind: esc[1], x: 18.5, y: 13.5 });
  // every other Colosse from the 110th fights at night (110, 310…: since iteration 49, the Tortillard holds 60, 160…)
  if (cycle % 4 === 2) { lvl.night = true; lvl.name = `Le Colosse de nuit · ${mission}`; }
  return lvl;
}

export function getMission(mission: number): ParsedLevel {
  if (mission <= LEVELS.length) return parseLevel(LEVELS[mission - 1]);
  if (EXTRA_LEVELS[mission]) return parseLevel(EXTRA_LEVELS[mission]);
  if (isBossMission(mission)) return bossLevel(mission);
  return proceduralLevel(mission);
}

/** Arenas for versus mode: handmade maps with enemies stripped, spawns in opposite corners. */
/** How many arenas the versus pool holds (a game starts on a random one of them, iteration 40). */
export const VERSUS_ARENAS = 19;
export function versusArena(round: number): ParsedLevel {
  // handmade missions, plus the tunnels of mission 22 (iteration 13), the belts of mission 25 (iteration 16), the rink of mission 27 (iteration 21), the ravine of mission 32 (iteration 33) and the dunes of mission 46 (iteration 36)
  const pool: LevelDef[] = [1, 2, 3, 5, 6, 7, 10, 12, 14, 15].map((i) => LEVELS[i]).concat(EXTRA_LEVELS[22], EXTRA_LEVELS[25], EXTRA_LEVELS[27], EXTRA_LEVELS[32], EXTRA_LEVELS[45], EXTRA_LEVELS[46], EXTRA_LEVELS[51], EXTRA_LEVELS[57], EXTRA_LEVELS[66]); // the snowmen of mission 66 (iteration 53), the snow of mission 57 (iteration 42), and the dunes of mission 46 (iteration 36), the switches of missions 45 and 51 (iteration 40)
  const base = parseLevel(pool[round % pool.length]);
  base.enemies = [];
  const corners: [number, number][] = [[1, 1], [W - 2, H - 2], [W - 2, 1], [1, H - 2]];
  base.spawns = corners.map(([cx, cy]) => nearestFree(base.tiles, cx, cy));
  base.night = round % 4 === 3; // every fourth round is fought in the dark
  base.storm = round % 5 === 2; // and one in five under a storm (from the third round)
  base.wind = round % 6 === 4 ? ((round * 3) % 8) * (Math.PI / 4) : undefined; // and one in six in the wind (iteration 23), from the fifth
  base.fog = round % 7 === 5 && !base.night && base.wind === undefined ? 3 + round : undefined; // and one in seven in the fog (iteration 26): hide and seek
  // « Le blizzard » (iteration 54): the snowy arenas, by day, every other time round the pool, are swept by squalls
  if (base.belts?.includes(SNOW) && !base.night && base.fog === undefined && Math.floor(round / pool.length) % 2 === 0) {
    base.blizzard = true;
    if (base.wind === undefined) base.wind = ((round * 3) % 8) * (Math.PI / 4);
  }
  return base;
}

export function nearestFree(tiles: number[], cx: number, cy: number, avoid: [number, number][] = []): [number, number] {
  for (let rad = 0; rad < 12; rad++) {
    for (let dy = -rad; dy <= rad; dy++) {
      for (let dx = -rad; dx <= rad; dx++) {
        if (Math.max(Math.abs(dx), Math.abs(dy)) !== rad) continue;
        const x = cx + dx, y = cy + dy;
        if (x < 0 || y < 0 || x >= W || y >= H) continue;
        if (tiles[y * W + x] !== Tile.Empty) continue;
        if (avoid.some(([ax, ay]) => Math.hypot(ax - (x + 0.5), ay - (y + 0.5)) < 0.9)) continue;
        return [x + 0.5, y + 0.5];
      }
    }
  }
  return [cx + 0.5, cy + 0.5];
}
