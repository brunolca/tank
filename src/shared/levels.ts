export interface ParsedLevel {
  name: string;
  tiles: number[];
  spawns: [number, number][];
  enemies: { kind: TankKind; x: number; y: number }[];
  night?: boolean;
  storm?: boolean;
  /** Wind (iteration 23): where it mainly blows, in radians (grid axes), when it blows. */
  wind?: number;
  /** Fog (iteration 26): the seed of the banks of mist, when there is fog. */
  fog?: number;
  /** « Le blizzard » (iteration 54): squalls of snow sweep the (windy) table now and then. */
  blizzard?: boolean;
  /** Floor layer: conveyor belts (iteration 16), ice (iteration 21) and sand (iteration 36), one code per cell (0 none, 1 right, 2 left, 3 up, 4 down, 5 ice, 6 sand), only when the map has some. */
  belts?: number[];
  /** « Le Tortillard » (iteration 49): the loop of rails its train runs round, flat [x0, y0, x1, y1…] (closed: the last point joins the first). */
  rail?: number[];
  /** Only these kinds of bonus crates fall here, and more often (iteration 52, see LevelDef.crates). */
  crates?: BonusKind[];
}

export function parseLevel(def: LevelDef): ParsedLevel {
  const tiles = new Array(W * H).fill(Tile.Empty);
  const spawns: [number, number][] = [];
  const enemies: ParsedLevel['enemies'] = [];
  let belts: number[] | undefined;
  for (let y = 0; y < H; y++) {
    const row = (def.map[y] ?? '').padEnd(W, '.');
    for (let x = 0; x < W; x++) {
      const c = row[x];
      const i = y * W + x;
      if (c === '#') tiles[i] = Tile.Wall;
      else if (c === 'H') tiles[i] = Tile.Tall;
      else if (c === 'o') tiles[i] = Tile.Cork;
      else if (c === '_') tiles[i] = Tile.Hole;
      else if (c === '*') tiles[i] = Tile.PortalA;
      else if (c === '+') tiles[i] = Tile.PortalB;
      else if (c === '=') tiles[i] = Tile.Tunnel;
      else if (c === BRIDGE_CHAR) tiles[i] = Tile.Bridge;
      else if (c === SNOWMAN_CHAR) tiles[i] = Tile.Snowman;
      else if (c === SWITCH_CHAR) tiles[i] = Tile.Switch;
      else if (c === RED_GATE_CHAR) tiles[i] = Tile.RedUp;
      else if (c === BLUE_GATE_CHAR) tiles[i] = Tile.BlueDown;
      else if (c === RED_LIFT_CHAR) tiles[i] = Tile.RedLift;
      else if (c === BLUE_LIFT_CHAR) tiles[i] = Tile.BlueSpan;
      else if ((BELT_CHARS as readonly string[]).includes(c)) (belts ??= new Array(W * H).fill(0))[i] = (BELT_CHARS as readonly string[]).indexOf(c) + 1;
      else if (c === ICE_CHAR) (belts ??= new Array(W * H).fill(0))[i] = ICE;
      else if (c === SAND_CHAR) (belts ??= new Array(W * H).fill(0))[i] = SAND;
      else if (c === SNOW_CHAR) (belts ??= new Array(W * H).fill(0))[i] = SNOW;
      else if (c >= '1' && c <= '4') spawns[+c - 1] = [x + 0.5, y + 0.5];
      else if (ENEMY_CHARS[c]) enemies.push({ kind: ENEMY_CHARS[c], x: x + 0.5, y: y + 0.5 });
    }
  }
  // « Les bonshommes de neige » (iteration 53): on a snowy table, a snowman stands in the snow, and falls into a heap of it
  if (belts?.includes(SNOW)) for (let i = 0; i < W * H; i++) if (tiles[i] === Tile.Snowman) belts[i] = SNOW;
  if (def.belts) {
    for (let y = 0; y < H; y++) {
      const row = def.belts[y] ?? '';
      for (let x = 0; x < W; x++) {
        if (tiles[y * W + x] !== Tile.Empty) continue; // the floor layer only covers floor (a tank may start on it)
        const k = (BELT_CHARS as readonly string[]).indexOf(row[x]);
        if (k >= 0) (belts ??= new Array(W * H).fill(0))[y * W + x] = k + 1;
        else if (row[x] === ICE_CHAR) (belts ??= new Array(W * H).fill(0))[y * W + x] = ICE;
        else if (row[x] === SAND_CHAR) (belts ??= new Array(W * H).fill(0))[y * W + x] = SAND;
        else if (row[x] === SNOW_CHAR) (belts ??= new Array(W * H).fill(0))[y * W + x] = SNOW;

      }
    }
  }
  return { name: def.name, tiles, spawns: spawns.filter(Boolean), enemies, night: def.night, storm: def.storm, belts, wind: def.wind === undefined ? undefined : (def.wind * Math.PI) / 180, fog: def.fog, blizzard: def.blizzard && def.wind !== undefined ? true : undefined, crates: def.crates };
}

// ---------- procedural missions (endless mode after the handmade campaign) ----------

export function rng(seed: number) {
  let s = seed >>> 0 || 1;
  return () => {
    s ^= s << 13; s >>>= 0;
    s ^= s >>> 17;
    s ^= s << 5; s >>>= 0;
    return s / 4294967296;
  };
}

const ROSTER_BY_TIER: TankKind[][] = [
  ['brown', 'ash', 'marine'],
  ['ash', 'marine', 'yellow', 'pink'],
  ['pink', 'green', 'yellow', 'violet'],
  ['violet', 'white', 'green', 'black'],
];

/** Options for generated missions: the daily challenge picks its own layout seed, portals, night and name. */
export interface GenOptions {
  seed?: number; portals?: boolean; night?: boolean; storm?: boolean; name?: string;
  /** Wind direction in radians, or false for a calm table. Campaign missions from the 33rd: about one in five is windy. */
  wind?: number | false;
  /** Fog seed, or false for a clear table. Campaign missions from the 37th: about one in five, by day and without wind (iteration 26). */
  fog?: number | false;
  /** Share of the enemies swapped for steel tanks (iteration 10). Campaign missions from the 21st: 0.22; the daily challenge: 0 unless its twist says so. */
  armored?: number;
  /** Share of the enemies swapped for Spectres (iteration 56): the daily twist « Nuit des spectres » only. */
  spectres?: number;
}

export function proceduralLevel(mission: number, opt: GenOptions = {}): ParsedLevel {
  const r = rng(opt.seed ?? mission * 7919 + 13);
  for (let attempt = 0; attempt < 30; attempt++) {
    const tiles = new Array(W * H).fill(Tile.Empty);
    const set = (x: number, y: number, t: Tile) => {
      // mirror horizontally around centre for a fair, symmetric look
      if (x < 0 || y < 0 || x >= W || y >= H) return;
      tiles[y * W + x] = t;
      tiles[(H - 1 - y) * W + (W - 1 - x)] = t;
    };
    const pieces = 5 + Math.floor(r() * 5);
    for (let p = 0; p < pieces; p++) {
      const t = r() < 0.55 ? Tile.Wall : r() < 0.5 ? Tile.Cork : r() < 0.6 ? Tile.Tall : Tile.Hole;
      const x0 = 3 + Math.floor(r() * (W - 6)), y0 = 1 + Math.floor(r() * (H - 2));
      const horiz = r() < 0.5, len = 2 + Math.floor(r() * 5);
      for (let k = 0; k < len; k++) set(horiz ? x0 + k : x0, horiz ? y0 : y0 + k, t);
      if (r() < 0.35) for (let k = 0; k < 3; k++) set(horiz ? x0 : x0 + k, horiz ? y0 + k : y0, t);
    }
    const free = (x: number, y: number) => tiles[y * W + x] === Tile.Empty;
    // clear spawn zone
    for (let y = 5; y <= 11; y++) for (let x = 1; x <= 4; x++) tiles[y * W + x] = Tile.Empty;
    const spawns: [number, number][] = [[2.5, 7.5], [2.5, 9.5]];
    // reachability flood from spawn
    const seen = new Uint8Array(W * H);
    const q = [7 * W + 2];
    seen[q[0]] = 1;
    while (q.length) {
      const i = q.pop()!;
      const x = i % W, y = (i / W) | 0;
      for (const [nx, ny] of [[x + 1, y], [x - 1, y], [x, y + 1], [x, y - 1]]) {
        if (nx < 0 || ny < 0 || nx >= W || ny >= H) continue;
        const j = ny * W + nx;
        if (!seen[j] && free(nx, ny)) { seen[j] = 1; q.push(j); }
      }
    }
    const cells: [number, number][] = [];
    for (let y = 0; y < H; y++) for (let x = 11; x < W; x++) if (seen[y * W + x]) cells.push([x, y]);
    if (cells.length < 30) continue;
    // fill unreachable pockets
    for (let i = 0; i < W * H; i++) if (!seen[i] && tiles[i] === Tile.Empty) tiles[i] = Tile.Wall;
    addPortals(tiles, seen, mission, cells, opt);
    // from the 45th, about half the missions throw a bridge over one of their pits (iteration 33): one more stream, and
    // only between two reachable cells, so nothing new opens up; the mirror keeps it fair (the daily challenge stays as it was)
    if (opt.seed === undefined && mission > 44) {
      const rb = rng(mission * 3907 + 83);
      if (rb() < 0.55) {
        const spans: number[] = [];
        for (let y = 1; y < H - 1; y++) for (let x = 1; x < W - 1; x++) {
          const i = y * W + x;
          if (tiles[i] !== Tile.Hole) continue;
          if ((seen[i - W] && seen[i + W] && tiles[i - 1] === Tile.Hole && tiles[i + 1] === Tile.Hole) || (seen[i - 1] && seen[i + 1] && tiles[i - W] === Tile.Hole && tiles[i + W] === Tile.Hole)) spans.push(i);
        }
        if (spans.length) {
          const i = spans[Math.floor(rb() * spans.length)];
          tiles[i] = Tile.Bridge;
          tiles[W * H - 1 - i] = Tile.Bridge;
        }
      }
    }
    // from the 47th, about two missions in five have dunes (iteration 36): patches of sand on the floor, mirrored like
    // the rest, on their own random stream (the walls and everything else stay put; the daily challenge stays as it was)
    let belts: number[] | undefined;
    if (opt.seed === undefined && mission > 46) {
      const rs = rng(mission * 6263 + 97);
      if (rs() < 0.4) {
        belts = new Array(W * H).fill(0);
        const blobs = 2 + Math.floor(rs() * 2);
        for (let k = 0; k < blobs; k++) {
          const cx = 6 + rs() * (W - 12), cy = 2 + rs() * (H - 4), rx = 1.6 + rs() * 1.8, ry = 1.4 + rs() * 1.6;
          for (let y = 0; y < H; y++) for (let x = 5; x < W - 5; x++) {
            const i = y * W + x;
            if (((x + 0.5 - cx) / rx) ** 2 + ((y + 0.5 - cy) / ry) ** 2 > 1) continue;
            if (tiles[i] === Tile.Empty) belts[i] = SAND;
            if (tiles[W * H - 1 - i] === Tile.Empty) belts[W * H - 1 - i] = SAND;
          }
        }
        if (!belts.some(Boolean)) belts = undefined;
      }
    }
    const tier = Math.min(3, Math.floor((mission - 1) / 8));
    const count = Math.min(8, 3 + Math.floor((mission - 16) / 3));
    const enemies: ParsedLevel['enemies'] = [];
    const used = new Set<number>();
    for (let e = 0; e < count; e++) {
      for (let tries = 0; tries < 40; tries++) {
        const [x, y] = cells[Math.floor(r() * cells.length)];
        const key = y * W + x;
        if (used.has(key) || used.has(key + 1) || used.has(key - 1) || used.has(key + W) || used.has(key - W)) continue;
        used.add(key);
        const roster = ROSTER_BY_TIER[Math.min(3, tier + (r() < 0.3 ? 1 : 0))];
        enemies.push({ kind: roster[Math.floor(r() * roster.length)], x: x + 0.5, y: y + 0.5 });
        break;
      }
    }
    // steel tanks (iteration 10) replace some of the enemies: own random stream, so walls, places and the other kinds stay put
    const armored = opt.armored ?? (opt.seed === undefined && mission > 20 ? 0.22 : 0);
    if (armored > 0) {
      const ra = rng((opt.seed ?? mission) * 6151 + 29);
      for (const e of enemies) if (ra() < armored) e.kind = 'steel';
      // a steel-tank mission always has at least one of them (and the daily twist even more)
      if (!enemies.some((e) => e.kind === 'steel') && (opt.armored ?? 0) > 0 && enemies.length) enemies[Math.floor(ra() * enemies.length)].kind = 'steel';
    }
    // the Maçon (iteration 12) takes over some of the others from the 22nd: yet another stream, nothing else moves
    if (opt.seed === undefined && mission > 21) {
      const rm = rng(mission * 4271 + 17);
      for (const e of enemies) if (e.kind !== 'steel' && rm() < 0.16) e.kind = 'mason';
    }
    // the Pilleur (iteration 15) slips in from the 25th: one more stream, at most two of them
    if (opt.seed === undefined && mission > 24) {
      const rt = rng(mission * 9029 + 41);
      let n = 0;
      for (const e of enemies) if (n < 2 && e.kind !== 'steel' && e.kind !== 'mason' && rt() < 0.09) { e.kind = 'thief'; n++; }
    }
    // the Rempart (iteration 22) holds the line from the 32nd: one more stream, at most two of them
    if (opt.seed === undefined && mission > 31) {
      const rr = rng(mission * 6007 + 53);
      let n = 0;
      for (const e of enemies) if (n < 2 && (e.kind === 'ash' || e.kind === 'yellow' || e.kind === 'pink' || e.kind === 'violet') && rr() < 0.14) { e.kind = 'rampart'; n++; }
    }
    // the Aimant (iteration 27) shows up from the 41st: one more stream, at most one of them
    if (opt.seed === undefined && mission > 40) {
      const rg = rng(mission * 7331 + 67);
      for (const e of enemies) if (e.kind !== 'steel' && e.kind !== 'mason' && e.kind !== 'thief' && e.kind !== 'rampart' && e.kind !== 'green' && e.kind !== 'brown' && rg() < 0.16) { e.kind = 'magnet'; break; }
    }
    // the Givré (iteration 31) skates in from the 43rd: one more stream, at most one of them
    if (opt.seed === undefined && mission > 42) {
      const rf = rng(mission * 8117 + 71);
      for (const e of enemies) if ((e.kind === 'ash' || e.kind === 'yellow' || e.kind === 'pink' || e.kind === 'violet' || e.kind === 'marine') && rf() < 0.2) { e.kind = 'frost'; break; }
    }
    // the Mortier (iteration 34) digs in from the 45th: one more stream, at most one of them, in place of a slow tank
    if (opt.seed === undefined && mission > 44) {
      const ro = rng(mission * 5413 + 79);
      for (const e of enemies) if ((e.kind === 'brown' || e.kind === 'ash' || e.kind === 'marine' || e.kind === 'green') && ro() < 0.22) { e.kind = 'mortar'; break; }
    }
    // the Sauterelle (iteration 41) leaps in from the 52nd: one more stream, at most one of them, in place of a mobile tank
    if (opt.seed === undefined && mission > 51) {
      const rh = rng(mission * 6271 + 89);
      for (const e of enemies) if ((e.kind === 'ash' || e.kind === 'yellow' || e.kind === 'pink' || e.kind === 'violet') && rh() < 0.2) { e.kind = 'hopper'; break; }
    }
    // the Veilleur (iteration 47) keeps watch from the 65th: one more stream, at most one of them, in place of a slow or a plain tank
    if (opt.seed === undefined && mission > 64) {
      const rl = rng(mission * 7193 + 97);
      for (const e of enemies) if ((e.kind === 'brown' || e.kind === 'ash' || e.kind === 'marine' || e.kind === 'violet' || e.kind === 'green') && rl() < 0.18) { e.kind = 'watcher'; break; }
    }
    // the Mécano (iteration 51) comes along from the 69th: one more stream, at most one of them, only with friends to repair
    if (opt.seed === undefined && mission > 68 && enemies.length >= 3) {
      const rr = rng(mission * 9241 + 101);
      for (const e of enemies) if ((e.kind === 'ash' || e.kind === 'yellow' || e.kind === 'pink' || e.kind === 'marine' || e.kind === 'violet' || e.kind === 'green' || e.kind === 'mason') && rr() < 0.14) { e.kind = 'mechanic'; break; }
    }
    // the Spectre (iteration 56) haunts the missions from the 73rd: one more stream, at most one of them, in place of a plain tank
    if (opt.seed === undefined && mission > 72 && enemies.length >= 2) {
      const rs = rng(mission * 8363 + 103);
      for (const e of enemies) if ((e.kind === 'ash' || e.kind === 'pink' || e.kind === 'violet' || e.kind === 'marine' || e.kind === 'white') && rs() < 0.15) { e.kind = 'spectre'; break; }
    }
    // the daily twist « Nuit des spectres » (iteration 56): a share of the enemies (never the steel ones), at least one
    if ((opt.spectres ?? 0) > 0 && enemies.length) {
      const rs = rng((opt.seed ?? mission) * 4513 + 107);
      for (const e of enemies) if (e.kind !== 'steel' && rs() < opt.spectres!) e.kind = 'spectre';
      if (!enemies.some((e) => e.kind === 'spectre')) enemies[Math.floor(rs() * enemies.length)].kind = 'spectre';
    }
    // about a third of the later generated missions are played at night (own random stream again)
    const night = opt.night ?? (mission > 20 && rng(mission * 31337 + 5)() < 0.32);
    // and about a quarter of them under a storm (yet another stream, so walls, portals and night stay put)
    const storm = opt.storm ?? (mission > 20 && rng(mission * 7717 + 3)() < 0.27);
    // and from the 33rd, about one in five has wind (iteration 23; one more stream, the daily challenge and the mole stay calm)
    let wind: number | undefined;
    if (opt.wind !== undefined) wind = opt.wind === false ? undefined : opt.wind;
    else if (opt.seed === undefined && mission > 32) {
      const rw = rng(mission * 5381 + 29);
      if (rw() < 0.22) wind = Math.floor(rw() * 8) * (Math.PI / 4);
    }
    // and from the 37th, about one in five of the calm days is foggy (iteration 26; one more stream again)
    let fog: number | undefined;
    if (opt.fog !== undefined) fog = opt.fog === false ? undefined : opt.fog;
    else if (opt.seed === undefined && mission > 36 && !night && wind === undefined) {
      const rf = rng(mission * 8123 + 61);
      if (rf() < 0.24) fog = 1 + Math.floor(rf() * 1000);
    }
    const name = fog !== undefined
      ? storm ? `Brume d’orage ${mission}` : `Mission de brume ${mission}`
      : wind !== undefined
      ? storm ? `Tempête ${mission}` : night ? `Nuit de vent ${mission}` : `Coup de vent ${mission}`
      : storm ? (night ? `Orage de nuit ${mission}` : `Mission d’orage ${mission}`) : night ? `Mission de nuit ${mission}` : belts ? `Mission des sables ${mission}` : `Mission spéciale ${mission}`;
    return { name: opt.name ?? name, tiles, spawns, enemies, night, storm, wind, fog, belts };
  }
  return parseLevel(LEVELS[0]);
}

/**
 * Later generated missions get one or two portal pairs, each linking the players' half to the enemies' half.
 * Its own random stream, so the walls of a mission stay the same whether it has portals or not.
 */
function addPortals(tiles: number[], seen: Uint8Array, mission: number, cells: [number, number][], opt: GenOptions) {
  const r = rng((opt.seed ?? mission) * 104729 + 7);
  if (opt.portals === false) return;
  if (opt.portals !== true && (mission < 19 || r() < 0.35)) return;
  const open = (x: number, y: number) =>
    seen[y * W + x] && [[0, 0], [1, 0], [-1, 0], [0, 1], [0, -1]].every(([dx, dy]) => tiles[(y + dy) * W + x + dx] === Tile.Empty);
  const pick = (x0: number, x1: number): [number, number] | undefined => {
    for (let tries = 0; tries < 60; tries++) {
      const x = x0 + Math.floor(r() * (x1 - x0)), y = 1 + Math.floor(r() * (H - 2));
      if (open(x, y)) return [x, y];
    }
    return undefined;
  };
  const pairs = r() < 0.4 ? 2 : 1;
  for (let p = 0; p < pairs; p++) {
    const a = pick(5, 10), b = pick(12, W - 2);
    if (!a || !b) continue;
    const t = p === 0 ? Tile.PortalA : Tile.PortalB;
    tiles[a[1] * W + a[0]] = t;
    tiles[b[1] * W + b[0]] = t;
  }
  // enemies never start on a portal
  for (let i = cells.length - 1; i >= 0; i--) if (tiles[cells[i][1] * W + cells[i][0]] !== Tile.Empty) cells.splice(i, 1);
}

